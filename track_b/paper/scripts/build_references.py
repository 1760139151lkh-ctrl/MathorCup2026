#!/usr/bin/env python3
"""Build a bibliography in actual first-citation order from chapter bibitems."""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

PAPER = Path(__file__).resolve().parents[1]


def uncomment(text: str) -> str:
    return re.sub(r"(?<!\\)%[^\n]*", "", text)


def tex_files(paper: Path, entry: str = "main.tex", seen=None) -> list[Path]:
    """TeX input paths are relative to the compilation root, not each section."""
    seen = set() if seen is None else seen
    path = (paper / entry).resolve()
    if path in seen or not path.is_file():
        return []
    if not path.is_relative_to(paper.resolve()):
        raise ValueError(f"TeX input escapes paper root: {entry}")
    seen.add(path)
    result = [path]
    for match in re.finditer(r"\\(?:input|include)\s*\{([^}]+)\}", uncomment(path.read_text(encoding="utf-8"))):
        name = match.group(1)
        result.extend(tex_files(paper, name if Path(name).suffix else name + ".tex", seen))
    return result


def expanded_tex(paper: Path, entry: str = "main.tex", stack=None) -> str:
    stack = set() if stack is None else stack
    path = (paper / entry).resolve()
    if not path.is_file():
        return ""
    if not path.is_relative_to(paper.resolve()):
        raise ValueError(f"TeX input escapes paper root: {entry}")
    if path in stack:
        raise ValueError(f"recursive TeX input: {entry}")
    text = uncomment(path.read_text(encoding="utf-8"))
    def replace(match):
        name = match.group(1)
        return expanded_tex(paper, name if Path(name).suffix else name + ".tex", stack | {path})
    return re.sub(r"\\(?:input|include)\s*\{([^}]+)\}", replace, text)


def citations(text: str) -> list[str]:
    keys = []
    pattern = r"\\(?:cite\w*|nocite)\*?(?:\s*\[[^\]]*\]){0,2}\s*\{([^}]+)\}"
    for match in re.finditer(pattern, text):
        for key in match.group(1).split(","):
            key = key.strip()
            if key and key not in keys:
                keys.append(key)
    return keys


def bibitems(path: Path) -> list[tuple[str, str]]:
    text = uncomment(path.read_text(encoding="utf-8"))
    text = re.sub(r"\\end\{thebibliography\}.*", "", text, flags=re.S)
    matches = list(re.finditer(r"\\bibitem(?:\s*\[[^\]]*\])?\s*\{([^}]+)\}", text))
    return [(m.group(1), text[m.start():matches[i + 1].start() if i + 1 < len(matches) else len(text)].strip())
            for i, m in enumerate(matches)]


def build(paper: Path) -> tuple[str, dict]:
    sources = sorted((paper / "evidence").glob("q[1-4]_references.tex"))
    common = paper / "evidence/common_references.tex"
    if common.exists():
        sources.append(common)
    definitions, origins, duplicates, conflicts = {}, {}, [], []
    for path in sources:
        for key, item in bibitems(path):
            if key in definitions:
                identical = re.sub(r"\s+", " ", definitions[key]) == re.sub(r"\s+", " ", item)
                duplicates.append({"key": key, "sources": [origins[key], str(path.relative_to(paper))], "identical": identical})
                if not identical:
                    conflicts.append(key)
            else:
                definitions[key], origins[key] = item, str(path.relative_to(paper))
    order = citations(expanded_tex(paper))
    missing = [key for key in order if key not in definitions]
    content = "% Generated by scripts/build_references.py; edit evidence/*_references.tex.\n"
    content += "\\begin{thebibliography}{99}\n"
    content += "\n\n".join(definitions[key] for key in order if key in definitions) + "\n"
    content += "\\end{thebibliography}\n"
    report = {"schema_version": 1, "passed": not missing and not conflicts,
              "citation_order": order, "reference_count": len(order) - len(missing),
              "sources": [str(p.relative_to(paper)) for p in sources],
              "duplicate_keys": duplicates, "conflicting_keys": conflicts, "missing_keys": missing,
              "unused_keys": sorted(set(definitions) - set(order))}
    return content, report


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--paper", type=Path, default=PAPER)
    args = parser.parse_args()
    paper = args.paper.resolve()
    content, report = build(paper)
    (paper / "qa").mkdir(parents=True, exist_ok=True)
    (paper / "qa/references_check.json").write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    if report["passed"]:
        (paper / "references.tex").write_text(content, encoding="utf-8")
    print(json.dumps(report, ensure_ascii=False))
    return 0 if report["passed"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
